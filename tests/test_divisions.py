"""
Tests for division-aware simulation.

Schedules are generated by randomly assigning teams to the slots of the
league's real schedule (fully random: teams can land in either division).
Playoffs: each division winner gets a spot, then wild cards by win %, with
total points as the tiebreaker. The rule is checked against ESPN's real seeds.
"""

import json
import random
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from get_espn_league_data import (
    parse_divisions,
    parse_schedule,
    write_league_settings,
    write_schedule_csv,
    write_scores_csv,
)
from simulate_schedule_permutations import (
    PlayoffSimulator,
    TemplateScheduleGenerator,
    load_league_structure,
)

FIXTURES = Path(__file__).parent / 'fixtures'


def load(name):
    return json.loads((FIXTURES / name).read_text())


@pytest.fixture
def season():
    """In-progress season: 12 teams, East/West, full 14-week schedule known."""
    return load('espn_in_progress_season.json')


def template_from(data):
    """Real schedule as weeks of (slot, slot), plus each slot's division."""
    weeks = {}
    for week, a, b in parse_schedule(data):
        weeks.setdefault(week, []).append((a, b))
    template = [weeks[w] for w in sorted(weeks)]
    return template, parse_divisions(data)


def make_generator(data, n_weeks=14, teams=None):
    template, slot_divisions = template_from(data)
    teams = teams or [f'P{slot}' for slot in sorted(slot_divisions)]
    return TemplateScheduleGenerator(template, slot_divisions, teams, n_weeks)


def pair_counts(schedule):
    return Counter(frozenset(m) for week in schedule for m in week)


# ------------------------------------------------------- shuffled real schedule

def test_template_schedule_is_truncated_to_played_weeks(season):
    schedule, _ = make_generator(season, n_weeks=8).generate()
    assert len(schedule) == 8


def test_template_schedule_preserves_structure(season):
    # Relabeling keeps how often pairs meet (36 once across, intra twice/once)
    random.seed(0)
    template, _ = template_from(season)
    template_meetings = sorted(pair_counts(template).values())
    for _ in range(20):
        schedule, _ = make_generator(season).generate()
        assert sorted(pair_counts(schedule).values()) == template_meetings
        for week in schedule:
            teams = [t for m in week for t in m]
            assert len(teams) == len(set(teams)) == 12


def test_divisions_follow_the_slot_each_team_lands_in(season):
    random.seed(1)
    gen = make_generator(season)
    schedule, divisions = gen.generate()
    assert Counter(divisions.values()) == {'East': 6, 'West': 6}
    # Teams sharing a division play each other more than once (as in the template)
    for pair, meetings in pair_counts(schedule).items():
        a, b = tuple(pair)
        if meetings == 2:
            assert divisions[a] == divisions[b]


def test_teams_are_randomized_across_divisions(season):
    random.seed(2)
    gen = make_generator(season)
    seen = {team: set() for team in gen.teams}
    for _ in range(200):
        _, divisions = gen.generate()
        for team, division in divisions.items():
            seen[team].add(division)
    assert all(found == {'East', 'West'} for found in seen.values())


def test_template_needs_one_slot_per_team(season):
    template, slot_divisions = template_from(season)
    with pytest.raises(ValueError):
        TemplateScheduleGenerator(template, slot_divisions, ['A', 'B'], 14)


def test_expected_win_pct_matches_all_play_with_template(season):
    # A uniformly random relabeling gives each team a uniformly random
    # opponent each week, so the all-play oracle still holds
    rng = np.random.default_rng(3)
    teams = [f'P{slot}' for slot in sorted(parse_divisions(season))]
    df = pd.DataFrame({'Player': teams, 'Record': ['0-0'] * 12})
    for w in range(1, 15):
        df[f'W{w}'] = rng.permutation(12) * 10.0 + rng.uniform(0, 5, 12)

    results = PlayoffSimulator(df, generator=make_generator(season, teams=teams)) \
        .run_simulation(1500).set_index('Player')

    scores = df[[f'W{w}' for w in range(1, 15)]].to_numpy()
    all_play = (scores[:, None, :] > scores[None, :, :]).sum(1).sum(1) / (11 * 14) * 100
    gap = np.abs(results.loc[teams, 'Expected Win %'].to_numpy() - all_play).max()
    assert gap < 1.5, f'max gap {gap:.2f} pp'


# ---------------------------------------------------------------- playoff rule

def record(wins, losses, points):
    return {'wins': wins, 'losses': losses, 'points_for': points}


def test_division_winner_makes_playoffs_even_with_weak_record():
    sim = PlayoffSimulator(pd.DataFrame({'Player': ['x'], 'Record': ['0-0'], 'W1': [0.0]}),
                           n_playoff_teams=2)
    records = {
        'E1': record(10, 4, 1500), 'E2': record(9, 5, 1400), 'E3': record(8, 6, 1300),
        'W1': record(5, 9, 1200), 'W2': record(4, 10, 1100),
    }
    divisions = {'E1': 'East', 'E2': 'East', 'E3': 'East', 'W1': 'West', 'W2': 'West'}
    assert sim.get_playoff_teams(records, divisions) == ['E1', 'W1']


def test_division_winner_tiebreak_uses_points():
    sim = PlayoffSimulator(pd.DataFrame({'Player': ['x'], 'Record': ['0-0'], 'W1': [0.0]}),
                           n_playoff_teams=2)
    records = {'A': record(7, 7, 1300), 'B': record(7, 7, 1400),
               'C': record(9, 5, 1000), 'D': record(8, 6, 1000)}
    divisions = {'A': 'West', 'B': 'West', 'C': 'East', 'D': 'East'}
    assert sim.get_playoff_teams(records, divisions) == ['C', 'B']


def test_no_divisions_ranks_overall():
    sim = PlayoffSimulator(pd.DataFrame({'Player': ['x'], 'Record': ['0-0'], 'W1': [0.0]}),
                           n_playoff_teams=2)
    records = {'A': record(10, 4, 1), 'B': record(9, 5, 1), 'C': record(3, 11, 1)}
    assert sim.get_playoff_teams(records) == ['A', 'B']


@pytest.mark.parametrize('fixture', ['espn_completed_season.json',
                                     'espn_in_progress_season.json'])
def test_playoff_rule_reproduces_espn_seeds(fixture):
    data = load(fixture)
    n = data['settings']['scheduleSettings']['playoffTeamCount']
    divisions = parse_divisions(data)
    records = {
        t['id']: record(t['record']['overall']['wins'], t['record']['overall']['losses'],
                        t['record']['overall']['pointsFor'])
        for t in data['teams']
    }
    espn_order = [t['id'] for t in sorted(data['teams'], key=lambda t: t['playoffSeed'])][:n]

    sim = PlayoffSimulator(pd.DataFrame({'Player': ['x'], 'Record': ['0-0'], 'W1': [0.0]}),
                           n_playoff_teams=n)
    assert sim.get_playoff_teams(records, divisions) == espn_order


# -------------------------------------------------------- loading league files

def test_load_league_structure_from_files(season, tmp_path):
    write_scores_csv(season, tmp_path / 'scores.csv')
    write_schedule_csv(season, tmp_path / 'schedule.csv')
    write_league_settings(season, tmp_path / 'settings.json')
    scores = pd.read_csv(tmp_path / 'scores.csv')

    structure = load_league_structure(scores, tmp_path / 'schedule.csv',
                                      tmp_path / 'settings.json')

    assert structure['n_playoff_teams'] == 6
    gen = structure['generator']
    assert isinstance(gen, TemplateScheduleGenerator)
    assert sorted(gen.teams) == sorted(scores['Player'])
    schedule, divisions = gen.generate()
    assert len(schedule) == 8  # only played weeks
    assert set(divisions) == set(scores['Player'])


def test_load_league_structure_falls_back_without_files(season, tmp_path):
    write_scores_csv(season, tmp_path / 'scores.csv')
    scores = pd.read_csv(tmp_path / 'scores.csv')
    structure = load_league_structure(scores, tmp_path / 'missing.csv',
                                      tmp_path / 'missing.json')
    assert structure == {'generator': None, 'n_playoff_teams': 6}
